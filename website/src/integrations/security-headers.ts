/**
 * Writes dist/_headers, the file Cloudflare Pages reads to add HTTP headers to every response.
 *
 * Why generate it instead of writing it by hand: the Content-Security-Policy forbids inline
 * scripts and styles unless their exact SHA-256 hash is listed. Astro adds a few small inline
 * blocks (the theme boot script, island loader), so after every build this scans the finished
 * HTML, hashes each inline <script> and <style>, and puts exactly those hashes in the policy.
 * Anything else injected later (by an attacker, an extension, a compromised dependency at
 * runtime) has a different hash and is blocked.
 *
 * The build fails if it finds inline event handlers (onclick="…") or style="…" attributes, since
 * the policy would silently block them in the browser.
 */
import type { AstroIntegration } from 'astro';
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

async function htmlFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await htmlFiles(path)));
    else if (entry.name.endsWith('.html')) out.push(path);
  }
  return out;
}

const sha256 = (text: string) => `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;

export function buildPolicy(scriptHashes: string[], styleHashes: string[]): string {
  return [
    // Deny everything by default, then allow only what the site actually uses.
    "default-src 'none'",
    // Our own script files, plus the exact inline blocks found in the build.
    ["script-src 'self'", ...scriptHashes].join(' '),
    ["style-src 'self'", ...styleHashes].join(' '),
    // data: is only for tiny inline SVG images in CSS; no remote images.
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    // The phone-level sky draws in a Web Worker (a script file from this site).
    "worker-src 'self'",
    "manifest-src 'self'",
    // The site must never be shown inside someone else's frame (clickjacking).
    "frame-ancestors 'none'",
    "base-uri 'none'",
    // There are no forms that send data anywhere.
    "form-action 'none'",
    "object-src 'none'",
    'upgrade-insecure-requests',
  ].join('; ');
}

export default function securityHeaders(): AstroIntegration {
  return {
    name: 'dayprism-security-headers',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const scripts = new Set<string>();
        const styles = new Set<string>();
        const problems: string[] = [];

        for (const file of await htmlFiles(root)) {
          const html = await readFile(file, 'utf8');
          for (const m of html.matchAll(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/gi)) {
            const attrs = m[1] ?? '';
            if (/\ssrc=/i.test(attrs)) continue; // external file: covered by 'self'
            if (/type=["']?application\/(ld\+)?json/i.test(attrs)) continue; // data, never executed
            if (m[2].trim() !== '') scripts.add(sha256(m[2]));
          }
          for (const m of html.matchAll(/<style(\s[^>]*)?>([\s\S]*?)<\/style>/gi)) {
            if (m[2].trim() !== '') styles.add(sha256(m[2]));
          }
          const rel = file.slice(root.length);
          if (/<[^>]+\son[a-z]+=/i.test(html)) problems.push(`${rel}: inline event handler (on…=) found`);
          if (/<[^>]+\sstyle=/i.test(html)) problems.push(`${rel}: style="…" attribute found`);
        }

        if (problems.length) {
          throw new Error(`Content-Security-Policy would block parts of the page:\n${problems.join('\n')}`);
        }

        const csp = buildPolicy([...scripts].sort(), [...styles].sort());
        const headers = `# Generated by src/integrations/security-headers.ts on every build. Do not edit by hand.

/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), serial=(), bluetooth=(), hid=(), midi=(), display-capture=(), browsing-topics=(), accelerometer=(self), gyroscope=(self), magnetometer=()
  X-Frame-Options: DENY
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin

/investors
  X-Robots-Tag: noindex, nofollow
  Cache-Control: private, no-store

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  Cache-Control: public, max-age=31536000, immutable
`;
        await writeFile(join(root, '_headers'), headers);
        logger.info(`_headers written: ${scripts.size} inline script hash(es), ${styles.size} inline style hash(es)`);
      },
    },
  };
}
